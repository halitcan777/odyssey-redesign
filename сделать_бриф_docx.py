"""Генерирует БРИФ_материалы_для_сайта.docx — что нужно от заказчика для наполнения."""
from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

RED = RGBColor(0xC8, 0x10, 0x2E)
GREY = RGBColor(0x66, 0x66, 0x66)

doc = Document()
st = doc.styles["Normal"]
st.font.name = "Helvetica"
st.font.size = Pt(10.5)

def h1(text):
    p = doc.add_paragraph()
    r = p.add_run(text.upper())
    r.font.size = Pt(20); r.font.bold = True
    p.space_after = Pt(4)
    return p

def h2(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(14); r.font.bold = True; r.font.color.rgb = RED
    p.paragraph_format.space_before = Pt(16)
    return p

def note(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(9.5); r.font.color.rgb = GREY
    return p

def table(rows):
    t = doc.add_table(rows=1, cols=4)
    t.style = "Table Grid"
    widths = [Cm(6.2), Cm(5.4), Cm(3.2), Cm(1.8)]
    hdr = t.rows[0].cells
    for i, name in enumerate(["Материал", "Зачем", "Формат", "Приор."]):
        hdr[i].text = name
        for par in hdr[i].paragraphs:
            for r in par.runs:
                r.font.bold = True; r.font.size = Pt(9.5)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = val
            for par in cells[i].paragraphs:
                for r in par.runs:
                    r.font.size = Pt(9.5)
    for col_i, w in enumerate(widths):
        for row in t.rows:
            row.cells[col_i].width = w
    return t

